export function coachFor(id: string, fallbackTip?: string): Coach {
  return (
    COACHES[id] || {
      setup: '材料备好，选她状态轻松的时间开始。',
      script: [
        '「我们今天玩这个，妈妈和你一起。」',
        fallbackTip ? `提示：${fallbackTip}` : '轻松玩就好，过程比结果重要。',
        '结束后问：「你最喜欢哪一步？」',
      ],
      watch: '兴趣与情绪；完成度比标准答案重要。',
      ifStuck: '不想做：缩短时间，或换自选角，明天再试。',
    }
  )
}
