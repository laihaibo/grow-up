/** 把活动条目编成具体可跟练的话术（避免空泛套话） */
export function coachFromActivity(a: Activity): Coach {
  const mats = a.materials || '不用特殊材料，家里/小区就能开始'
  const title = a.title
  const steps = a.steps.length ? a.steps : ['先示范一次，再让她上手', '完成后一起回顾最喜欢哪一步']
  const domainHint: Record<string, string> = {
    health: '注意安全与热身，强度以她能笑出声为准',
    language: '她说错不打断，先说完再轻轻重述正确说法',
    social: '你先示范一次「好听的说话方式」，再请她试',
    science: '鼓励先猜再验，猜错也要说「科学家也猜错」',
    art: '不评价像不像，只问「这里发生了什么」',
  }
  const script: string[] = [
    `开场蹲下平视：「今天玩《${title}》，大约 ${a.minutes} 分钟。妈妈和你一起，规则可以商量。」`,
    `材料与场景：${mats}。摆好后指给她看，避免边找东西边催。`,
    ...steps.map(
      (step, i) =>
        `第 ${i + 1} 步照做：${step}。你说出这一步的目标，再示范一次，然后说「轮到你」。`,
    ),
    domainHint[a.domain] || '过程比结果重要',
    a.tip
      ? `跟练提醒：${a.tip}`
      : '她若自己改成别的玩法，先跟她的玩法，清单明天再完成也来得及。',
    `结束具体表扬：「你刚才____（描述你看到的行为）做得很好。」空格处必须是真实细节，不说「真棒」就完事。`,
    `回问一句：「最喜欢哪一步？明天还想玩，还是想换自选角？」`,
  ]

  const watch =
    a.focus.includes('hanzi') || a.focus.includes('english') || a.focus.includes('math')
      ? '是否指认/点数/跟读有实质动作；兴趣掉下来就停，不硬凑时长。'
      : a.focus.includes('motor')
        ? '动作是否安全协调；有没有还想再来一次。'
        : a.focus.includes('social') || a.id.startsWith('brave-')
          ? '有没有把话说完整；事后情绪是松还是紧。'
          : '是否好奇、愿意再试；完成度比标准答案重要。'

  const ifStuck = a.tip
    ? `卡住时：${a.tip} 也可以只做前 2 步就结束。`
    : '卡住时：把时长砍半；你做完给她看；或改她当老师来指挥你。'

  return { setup: `约 ${a.minutes} 分钟 · ${mats} · 手机静音`, script, watch, ifStuck }
}

export function coachFor(id: string, fallbackTip?: string, activity?: Activity): Coach {
  if (COACHES[id]) return COACHES[id]
  if (activity) return coachFromActivity(activity)
  return coachFromActivity({
    id,
    title: id,
    domain: 'language',
    focus: ['speak'],
    minutes: 12,
    steps: ['先示范，再让她做', '完成后回顾最喜欢哪一步'],
    tip: fallbackTip,
  })
}
