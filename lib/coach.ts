export function coachFor(id: string, fallbackTip?: string): Coach {
  return (
    COACHES[id] || {
      setup: '材料备好；选她吃饱、不困、情绪稳的时间；手机静音；预计 10–15 分钟。',
      script: [
        '开场说明：「今天我们玩这个，妈妈和你一起，规则可以改，开心最重要。」',
        '示范一次完整流程，边做边说，让她看懂再上手。',
        '「现在轮到你。需要帮忙就说停，妈妈在。」',
        fallbackTip ? `跟练提醒：${fallbackTip}` : '轻松玩就好，过程比结果重要。',
        '中途观察兴趣，下降就减量或改规则，不硬撑到时间结束。',
        '结束后具体表扬：「你刚才……（描述具体行为）做得很好。」',
        '「你最喜欢哪一步？明天还想不想玩？」把答案记在心里。',
      ],
      watch: '兴趣、情绪、是否愿意再玩一次。完成度比标准答案重要。',
      ifStuck: '不想做 → 缩短到 5 分钟；或她出题你来做；或改到明天，今天换自选角。',
      bonus: '让她当一次老师，教玩偶或家长做一遍。',
    }
  )
}
